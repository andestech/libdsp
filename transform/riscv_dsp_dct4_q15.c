/**
 * @brief Function to implement the q15 DCT type IV function.
 * @param[in]       *src     points to the input block data.
 * @param[in]       m        If not defined STATIC_VERSION, the data buffer
 *                           is of size 2 * n while n = 2 ** m.
 * @return none.
 */

/* function description */
/**
 * @brief riscv_dsp_dct4_q15
 *
 *            N-1
 *     y[k] = sum x[n] * cos(PI * (2 * k + 1) * (2 * n + 1) / (4 * N))
 *            n=0
 *
 * Implementation of N such that
 *   1] N = 8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192, and 16384.
 *   2] m, defined as log2(N), is less than RES_LOGN.
 */

void riscv_dsp_dct4_q15(q15_t *src, uint32_t m)
{
    /* N > 4: (N / 2) * log2(N) + N / 4 multiplications/divisions */
    /*        (2 * N) * log2(N) - 9 * N / 4 + 1
     **                        additions/subtractions */
    /*  (only (3 * N / 2) * log2(N) - 5 * N / 4 + 1 if maintaining
     **      table of 1 / (2 * cosine)) */
    uint32_t n = (1 << m);
    uint32_t factor = 1 << (RES_LOGN - 2 - m);
    const q15_t *scale = &riscv_dsp_cos_table_q15_linear[(factor >> 1)];
    uint32_t k = 0;

#ifdef ENA_DSP_ISA_32
    for (k = 0; k < n; k += 2, scale += factor << 1)
    {
        suni_t quad_src = simd_load_16(&src[k], 0);
        q31_t tmp_scale1 = NDS_DSP_PKBB16(*(scale + factor), *scale);
        q31_t result = NDS_DSP_KHM16(quad_src.l0, tmp_scale1);
        simd_save_16(&src[k], result);
    }
#else
    for (k = 0; k < n; k++, scale += factor)
    {
        src[k] = (src[k] * (*scale)) >> 15;
    }
#endif

    /* do dct */
    riscv_dsp_dct_q15(src, m);

    src[0] >>= 1;
    for (k = 1; k < n; k++)
    {
        src[k] = src[k] - src[k - 1];
    }
}


/**
 * @brief riscv_dsp_idct4_q15
 *
 *            2   N-1
 *     y[k] = - * sum x[n] * cos(PI * (2 * k + 1) * (2 * n + 1) / (4 * N))
 *            N   n=0
 *
 * Functions include:
 *  1. riscv_dsp_idct4_o_q15 : Internal work function for DCT-IV, used by
 *                         riscv_dsp_idct4_e_q15.
 *  2. riscv_dsp_idct4_e_q15 : idct main function.
 */

/**
 * @brief riscv_dsp_idct4_o_q15
 */
#ifdef DCT_OLD_VER
static void riscv_dsp_idct4_o_q15(q15_t *src, uint32_t m)
{
    /* induction functions from 2, 3, 4, ..., FFT_LOGN */
    if (2 != m)
    {
        /* N > 4: (N / 2) * log2(N) + N / 4 (multiplications/divisions)
         **       (2 * N) * log2(N) - 9 * N / 4 + 1
         **                    (additions/subtractions) */
        /*  (only (3 * N / 2) * log2(N) - 5 * N / 4 + 1 if maintaining
         ** table of 1 / (2 * cosine)) */
        uint32_t n = 1 << m;
        uint32_t factor;
        const unsigned short *scale;

        /* pre-processing */
        /* example of n = 8:
         * input:  [a, b, c, d, e, f, g, h]
         * output: [a, a+b, b+c, c+d, d+e, e+f, f+g, g+h]
         */
        uint32_t k;
        k = n - 1;
        while (k != 0)
        {
            src[k] = src[k] + src[k - 1];
            k--;
        }

        /* do idct */
        riscv_dsp_idct_o_q15(src, m);

        /* post-processing */
        /* example of n = 8:
         * input:  [a, b, c, d, e, f, g, h]
         * output: [a/cos(1/32), b/cos(3/32),  c/cos(5/32),  d/cos(7/32),
         *          e/cos(9/32), f/cos(11/32), g/cos(13/32), h/cos(15/32)]
         */
        factor = 1 << (RES_LOGN - 2 - m);
        scale = &riscv_dsp_cos_recip_table_q15[(factor >> 1)];

        while (k != n)
        {
            src[k] = ((src[k]) * (*scale)) >> (19 - RES_LOGN);
            k++;
            scale += factor;
        }
    }
    else
    {
        /* N = 4: 8 multiplications/divisions
         **       12 additions/subtractions */

        q31_t w0, w1, w2, w3, tmp;  /* Temporary variable */
        w0 = src[0];    /* w0 = x0 */
        /* pre-processing */
        w1 = src[1];
        w2 = src[2];
        w3 = src[3];
        w3 += w2;       /* w3 = x2 + x3 */
        w2 += w1;       /* w2 = x1 + x2 */
        w1 += w0;       /* w1 = x0 + x1 */

        /* even portion */
        tmp = (w2 * DCT_COEF4_Q15) >> 15;
        w2 = w0 - tmp;    /* z1 = w0 - w2 * cos(PI / 4) */
        w0 = w0 + tmp;    /* z0 = w0 + w2 * cos(PI / 4) */

        tmp = ((w1 + w3) * DCT_COEF4_Q15) >> 15;
        /* z2 = x1 * cos(3 * PI / 8) - x3 * cos(PI / 8) */
        w3 = ((w1 + tmp) * DCT_COEF2_R_Q15) >> 17;
        /* z3 = x1 * cos(PI / 8) + x3 * cos(3 * PI / 8) */
        w1 = ((w1 - tmp) * DCT_COEF6_R_Q15) >> 17;

        /* modified butterfly */
        /* y0 = z0 + z2 */
        src[0] = ((w0 + w3) * DCT_COEF1_R_Q15) >> 17;
        /* y3 = z0 - z2 */
        src[3] = ((w0 - w3) * DCT_COEF7_R_Q15) >> 17;
        /* y1 = z1 + z3 */
        src[1] = ((w2 + w1) * DCT_COEF3_R_Q15) >> 17;
        /* y2 = z1 - z3 */
        src[2] = ((w2 - w1) * DCT_COEF5_R_Q15) >> 17;
    }
}
#endif //DCT_OLD_VER
/**
 * @brief riscv_dsp_idct4_e_q15
 */

#ifdef DCT_OLD_VER
static void riscv_dsp_idct4_e_q15(q15_t *src, uint32_t m)
{
    q31_t tmp;

    /* induction functions from 2, 3, 4, ..., FFT_LOGN */
    if (2 != m)
    {
        /*  N > 4: (N / 2) * log2(N) + N / 4 (multiplications/divisions)
         **        (2 * N) * log2(N) - 9 * N / 4 + 1
         **                        (additions/subtractions) */
        /*   (only (3 * N / 2) * log2(N) - 5 * N / 4 + 1 if maintaining
         ** table of 1 / (2 * cosine)) */
        uint32_t n = (1 << m);
        uint32_t k = (n >> 1);
        q15_t swap_buf[k];
        q15_t *ptre = &src[0], *ptro = &src[n], *ptrz;
        q15_t *ptrx = &swap_buf[0];

        /* pre-processing */
        /* example of n = 8:
         * input:  [a, b, c, d, e, f, g, h]
         * output: [a+h, b+g, c+f, d+e, -, -, -, -] and [a-h, b-g, c-f, d-e]
         */

        do
        {
            q31_t data = *ptre;
            ptro--;
            tmp = *ptro;
            *ptrx++ = data - tmp;
            *ptre++ = data + tmp;
        }
        while (ptre != ptro);

        /* even portion */
        riscv_dsp_idct4_e_q15(src, m - 1);

        /* odd portion */
        riscv_dsp_idct4_o_q15(swap_buf, m - 1);

        /* post-processing - shuffle */
        /* example of n = 8:
         * input:  [a, b, c, d, -, -, -, -] and [e, f, g, h]
         * output: [a, e, b, f, c, g, d, h]
         */
        ptrx--;
        ptre--;
        ptro = &src[0];
        ptrz = &src[n - 1];
        do
        {
            *ptrz-- = *ptrx--;
            *ptrz-- = *ptre--;
        }
        while (ptre != ptro);
        *ptrz = *ptrx;
    }
    else
    {
        /* N = 4: 5 (multiplications/divisions) */
        /*        8 (additions/subtractions) */
        q31_t w0, w1, w2, w3;

        /* butterfly */
        w0 = src[0];
        tmp = src[3];
        w2 = w0 - tmp;     /* w2 = x0 - x3 */
        w0 = w0 + tmp;     /* w0 = x0 + x3 */
        w1 = src[2];
        tmp = src[1];
        w3 = tmp - w1;     /* w3 = x1 - x2 */
        w1 = tmp + w1;     /* w1 = x1 + x2 */

        /* even portion */
        src[0] = w0 + w1;                /* y0 = w0 + w1 */
        /* y2 = (w0 - w1) * cos(PI / 4) */
        src[2] = ((w0 - w1) * DCT_COEF4_Q15) >> 15;

        /* odd portion */
        /* y1 = w2 * cos(PI / 8) + w3 * cos(3 * PI / 8) */
        src[1] = (w2 * DCT_COEF2_Q15 + w3 * DCT_COEF6_Q15) >> 15;
        /* y3 = w2 * cos(3 * PI / 8) - w3 * cos(PI / 8) */
        src[3] = (w2 * DCT_COEF6_Q15 - w3 * DCT_COEF2_Q15) >> 15;
    }
}
#endif // DCT_OLD_VER
