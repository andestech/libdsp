void riscv_dsp_idct4_q31(q31_t *src, uint32_t m)
{
    /* DCT_IV */
#ifdef DCT_OLD_VER
    uint32_t n = (1 << m);
    uint32_t factor = 1 << (RES_LOGN - 2 - m);
    const q31_t *scale = &riscv_dsp_cos_table_q31_linear[(factor >> 1)];

    /* pre-processing */
    /* example of n = 8:
     * input:  [a, b, c, d, e, f, g, h]
     * output: [a*cos(1/32), b*cos(3/32),  c*cos(5/32),  d*cos(7/32),
     *          e*cos(9/32), f*cos(11/32), g*cos(13/32), h*cos(15/32)]
     */
    uint32_t k;
    for (k = 0; k < n; k++, scale += factor)
    {
        src[k] = ((q63_t)src[k] * (*scale)) >> 31;
    }

    riscv_dsp_idct4_e_q31(src, m);

    /* post-processing */
    /* example of n = 8:
     * input:  [a, b, c, d, e, f, g, h]
     * output: [A=a>>1, B=b-A, C=c-B, D=d-C, E=e-D, F=f-E, G=g-F, H=h-G]
     */
    q31_t data = src[0] << 2;
    for (k = 1; k < n; k++, scale += factor)
    {
        data = (src[k] << 3) - data;
        src[k] = data;
    }
#else //DCT_OLD_VER
    // new version using the same implmentation in libvec dct4,
    // TYPE_IDCT4
    uint32_t n = 1 << m;
    uint32_t n_h = n >> 1;
    //uint32_t tbl1_start = 0;
    uint32_t tbl1_step = 0;
    uint32_t tbl2_start = 0;
    uint32_t tbl2_step = 0;
    uint32_t i, j;
    q63_t tmp1, tmp2;

    // the table only support up to 1024-points idct4
    //tbl1_start = 0;
    tbl1_step = 1 << (10 - m);
    tbl2_start =  1 << (10 - m) ;
    tbl2_step = 2 * tbl2_start;

    //  for 2-times n_h rfft using
    q31_t * tmp = NDSV_MALLOC(sizeof(q31_t) * (n + 2));


    q31_t *out1 = (q31_t *) &tmp[0];
    q31_t *out2 = (q31_t *) &tmp[n_h];

    // due to the q-format difference between livcec and libdsp
    // (Q2.30 in libdsp / Q3.29 in libvec.)
    // and to prevent overflow during the calculation
    // adding pre-bits and changing the post-bits in libdsp.
    int post_bits = IDCT4_COS_BITS - 3;
    int pre_bits  = 1;

    tmp[0] = src[0] >> pre_bits;
    tmp[n_h] = src[n - 1] >> pre_bits;
    for (i = 1, j = (tbl1_step) ; i + i < n_h; i++, j += tbl1_step )
    {
        int ci = i * 2;
        q31_t u, v, a, b, a2, b2;

        u = src[ci - 1] >> pre_bits;
        v = src[ci] >> pre_bits;
        a = u + v;
        b2 = u - v;

        u = src[n - ci - 1] >> pre_bits;
        v = src[n - ci] >> pre_bits;
        b = u + v;
        a2 = u - v;

        q31_t co, si;
        co = cos_table1[j];
        si = sin_table1[j];

        q31_t apb, amb;
        apb = a + b;
        amb = a - b;
        tmp1 = (q63_t) (((q63_t)co * amb + (q63_t)si * apb) >> (IDCT4_COS_BITS + 1));
        tmp2 = (q63_t) (((q63_t)co * apb - (q63_t)si * amb) >> (IDCT4_COS_BITS + 1));
        tmp[i] = (q31_t) tmp1;
        tmp[n_h - i] = (q31_t) tmp2;


        apb = a2 + b2;
        amb = a2 - b2;
        tmp1 = (((q63_t)co * amb + (q63_t)si * apb) >> (IDCT4_COS_BITS + 1));
        tmp2 = (((q63_t)co * apb - (q63_t)si * amb) >> (IDCT4_COS_BITS + 1));
        tmp[n_h + i] = (q31_t) tmp1;
        tmp[n - i]   = (q31_t) tmp2;

    }
    // i = n_h/2, j = (n_h/2) * (tbl1_start + n_h/2*tbl1_step)
    q31_t u, v;
    u = src[n_h - 1] >> pre_bits;
    v = src[n_h] >> pre_bits;

    tmp1 = (q63_t)(u + v) * (cos_table1[j]) >> IDCT4_COS_BITS;
    tmp2 = (q63_t)(u - v) * (cos_table1[j]) >> IDCT4_COS_BITS;
    tmp[i] = (q31_t) tmp1;
    tmp[n - i] = (q31_t) tmp2;

    // rfft
    if(m == 3)
    {
        vec_four_point_rfft_q31(&tmp[0]);
        vec_four_point_rfft_q31(&tmp[n_h]);
    }
    else
    {
        riscv_dsp_rfft_q31_noscale(&tmp[0], (m - 1) );
        riscv_dsp_rfft_q31_noscale(&tmp[n_h], (m - 1) );
    }

    // post-processing
    q31_t *co, *si;
    q31_t a, b;
    co = &cos_table2[tbl2_start]; /* cos */
    si = &sin_table2[tbl2_start]; /* sin */
    a = out1[0];
    b = out2[0];
    tmp1 = (q63_t) ((q63_t)(*co) * a + (q63_t)(*si) * b) >> post_bits;
    tmp2 = (q63_t) ((q63_t)(*si) * a - (q63_t)(*co) * b) >> post_bits;
    src[0] = (q31_t) tmp1;
    src[n - 1] = (q31_t) tmp2;

    co += tbl2_step;
    si += tbl2_step;
    for (i = 1; i + i < n_h; ++i)
    {
        int k, ci = i * 2;
        q31_t u, v, u2, v2;
        u = out1[ci];
        v = out1[ci + 1];
        u2 = out2[ci];
        v2 = out2[ci + 1];
        k = (i + i) - 1;

        a = u - v;
        b = v2 - u2;
        tmp1 = (q63_t) ((q63_t)(*co) * a + (q63_t)(*si) * b) >> post_bits;
        tmp2 = (q63_t) ((q63_t)(*si) * a - (q63_t)(*co) * b) >> post_bits;
        src[k] = (q31_t) tmp1;
        src[n - 1 - k] = (q31_t) tmp2;

        k++;
        co += tbl2_step;
        si += tbl2_step;

        a = u + v;
        b = u2 + v2;

        tmp1 = ((q63_t)(*co) * a + (q63_t)(*si) * b) >> post_bits;
        tmp2 = ((q63_t)(*si) * a - (q63_t)(*co) * b) >> post_bits;

        src[k] = (q31_t) tmp1;
        src[n - 1 - k] = (q31_t) tmp2;

        co += tbl2_step;
        si += tbl2_step;
    }
    int k = (i + i) - 1;
    a = out1[1];   // rfft out [r[0], r[N/2], r[1],i[1], ...];
    b = out2[1];   // rfft out [r[0], r[N/2], r[1],i[1], ...];

    tmp1 = (q63_t) ((q63_t)(*co) * a - (q63_t)(*si) * b) >> post_bits;
    tmp2 = (q63_t) ((q63_t)(*si) * a + (q63_t)(*co) * b) >> post_bits;
    src[k] = (q31_t) tmp1;
    src[n - 1 - k] = (q31_t) tmp2;

    NDSV_FREE(tmp);


#endif //DCT_OLD_VER

}

