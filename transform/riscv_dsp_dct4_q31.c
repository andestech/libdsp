static inline void vec_four_point_rfft_q31(q31_t * src)
{
    q31_t a = src[0] + src[2];
    q31_t b = src[0] - src[2];
    q31_t c = src[1] + src[3];
    q31_t d = src[1] - src[3];
    src[0] = (a + c);
    src[1] = (a - c);
    src[2] = (b);
    src[3] = (-d);
}

