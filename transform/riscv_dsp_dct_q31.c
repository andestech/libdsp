/**
 * @brief Function to implement the q31 DCT Functions
 * @param[in]       *src     points to the input block data.
 * @param[in]       m        If not defined STATIC_VERSION, the data buffer
 *                           is of size 2 * n while n = 2 ** m.
 * @return none.
 */

void riscv_dsp_dct_q31(q31_t *src, uint32_t m)
{
#ifdef DCT_OLD_VER
    riscv_dsp_dct_e_q31(src, m);
#else //DCT_OLD_VER

    uint32_t n = 1 << m;
    int i, j;

    q31_t * tmp = NDSV_MALLOC(sizeof(q31_t) * n);

    // pre-processing
    for (i = 0, j = 0; i < (int)n; i+=2, j++)
    {
        tmp[j] = src[i];
        tmp[n-j-1] = src[i+1];
    }

    // rfft
    riscv_dsp_rfft_q31(tmp, m);

    // post-processing
    src[0] = tmp[0] << RESCALE_BITS;
    int level = 1 << (COS_LOGN-m);
    for (i = 1, j = level; i < (int)n - i; i++, j+=level)
    {
        int ci = i * 2;
        q31_t re, im, co, si;
        re = tmp[ci];
        im = tmp[ci+1];
        co = test_cos_table[j];
        si = test_cos_table[COS_N-j];

        src[i]   = (q31_t)(((q63_t)co * re + (q63_t)si * im) >> (COS_BITS-RESCALE_BITS));
        src[n-i] = (q31_t)(((q63_t)si * re - (q63_t)co * im) >> (COS_BITS-RESCALE_BITS));
    }
    src[i] = (q31_t)(((q63_t)test_cos_table[j] * tmp[1]) >> (COS_BITS-RESCALE_BITS));

    NDSV_FREE(tmp);    
#endif //DCT_OLD_VER
}

/**
 * @brief Function to implement the q31 IDCT Functions
 * @param[in]       *src     points to the input block data.
 * @param[in]       m        If not defined STATIC_VERSION, the data buffer
 *                           is of size 2 * n while n = 2 ** m.
 * @return none.
 */

void riscv_dsp_idct_q31(q31_t *src, uint32_t m)
{
#ifdef DCT_OLD_VER
    riscv_dsp_idct_e_q31(src, m);
#else //DCT_OLD_VER
    uint32_t n = 1 << m;
    q31_t nfactor = (1.0f / n) * COS_MUL;
    int i, j;

    // pre-processing
    int level = 1 << (COS_LOGN-m);
    for (i = 1, j = level; i < (int)n - i; i++, j+=level)
    {
        q31_t a, b, apb, amb, co, si;
        a = src[i];
        b = src[n-i];
        apb = a + b;
        amb = a - b;
        co = test_cos_table[j];
        si = test_cos_table[COS_N-j];

        src[i]   = (q31_t)(((q63_t)co * amb + (q63_t)si * apb) >> (COS_BITS));
        src[n-i] = (q31_t)(((q63_t)co * apb - (q63_t)si * amb) >> (COS_BITS));
    }
    src[i] = (q31_t)((((q63_t)src[i] * test_cos_table[j])) >> (COS_BITS-1));

    // rfft
    riscv_dsp_rfft_q31_noscale(src, m);

    // post-processing
    src[0] = (q31_t)(((q63_t)src[0] * nfactor) >> (COS_BITS - m));
    q31_t tmp = src[1];
    for (i = 1; i < (int)n - i; i++)
    {
        int ci = i * 2;
        q31_t re, im;
        re = src[ci];
        im = src[ci + 1];

        src[ci-1] = (q31_t)(((q63_t)(re - im) * nfactor) >> (COS_BITS - m ));
        src[ci] = (q31_t)(((q63_t)(re + im) * nfactor) >> (COS_BITS - m ));
    }
    src[i * 2 - 1] = (q31_t)(((q63_t)tmp * nfactor) >> (COS_BITS - m));

#endif //DCT_OLD_VER
}

